import assert from 'node:assert/strict'

const base = process.env.LINEUP_PREVIEW_TEST_URL
if (process.env.LINEUP_LOCAL_E2E !== '1' || !base || !['localhost', '127.0.0.1'].includes(new URL(base).hostname)) throw new Error('Development preview checks require an explicit loopback test URL.')
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ?? 'playwright')
const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
page.setDefaultTimeout(60000)
const errors = []
page.on('pageerror', error => errors.push(error.message))
page.on('console', message => {
  if (message.type() === 'error') {
    console.log('DEV_PREVIEW_CONSOLE_ERROR ' + message.text())
    if (!message.text().startsWith('Failed to load resource:')) errors.push(message.text())
  }
})
try {
  const production = await page.request.get('http://localhost:3001/dev-preview')
  assert.equal(production.status(), 404, 'Production must not expose the development preview')
  assert.equal((await production.text()).includes('Sample data. Explore both dashboards'), false)
  await page.goto(base + '/login')
  await page.getByRole('link', { name: 'Preview without an account', exact: false }).click()
  await page.getByRole('region', { name: 'Development preview', exact: true }).waitFor()
  assert.equal(await page.getByTestId('metric-ticket').textContent(), '72')
  const pending = page.getByRole('region', { name: 'Pending review', exact: true })
  assert.ok(await pending.evaluate(node => Boolean(node.closest('.workspace-priorities')?.nextElementSibling?.classList.contains('dashboard-columns'))))
  const summaryBox = await page.getByRole('region', { name: 'Event summary', exact: true }).boundingBox()
  const pendingBox = await pending.boundingBox()
  assert.ok(summaryBox && pendingBox && pendingBox.y < summaryBox.y, 'Pending review should sit above the metrics')
  const updates = page.getByRole('region', { name: 'Recent updates', exact: true })
  const latest = updates.getByRole('article', { name: 'New registration for Open-Air Cinema', exact: true })
  await latest.getByText('Latest update', { exact: true }).waitFor()
  assert.equal(await updates.getByRole('list').getByText('Open-Air Cinema', { exact: true }).count(), 0)
  assert.ok(await updates.evaluate(node => node.previousElementSibling?.getAttribute('aria-labelledby') === 'spotlight-title'))
  assert.equal(await page.getByTestId('metric-circle-check').textContent(), '18')
  await page.getByRole('link', { name: 'Create event', exact: true }).waitFor()
  const map = page.getByRole('region', { name: 'Venue map', exact: true })
  const mapFrame = map.locator('iframe')
  assert.equal(await mapFrame.count(), 0)
  await map.getByRole('link', { name: 'Get directions' }).waitFor()
  await page.route('https://www.openstreetmap.org/**', route => route.abort())
  await map.getByRole('button', { name: /The Makers’ Meet/ }).click()
  assert.equal(await map.getByRole('button', { name: /The Makers’ Meet/ }).getAttribute('aria-pressed'), 'true')
  await map.getByRole('button', { name: 'Open interactive map' }).click()
  const mapDialog = map.getByRole('dialog', { name: 'Perdana Botanical Garden', exact: true })
  assert.equal(await mapFrame.getAttribute('title'), 'Map of Perdana Botanical Garden')
  await mapDialog.getByRole('link', { name: 'Get directions' }).waitFor()
  await mapDialog.getByRole('button', { name: 'Close map' }).click()
  await mapFrame.waitFor({ state: 'detached' })
  await mapDialog.waitFor({ state: 'hidden' })
  await page.unroute('https://www.openstreetmap.org/**')
  assert.match(await map.getByRole('link', { name: 'Get directions' }).getAttribute('href'), /destination=3\.1437%2C101\.6838/)
  await page.getByRole('region', { name: 'Ticket & attendance', exact: true }).getByText('25%', { exact: true }).waitFor()
  const ticketPanel = page.getByRole('region', { name: 'Ticket & attendance', exact: true })
  await ticketPanel.getByText('48 registered', { exact: true }).waitFor()
  await ticketPanel.getByRole('button', { name: 'Check-ins', exact: true }).click()
  await ticketPanel.getByText('Creative Coding Lab', { exact: true }).waitFor()
  await ticketPanel.getByText('18 checked in', { exact: true }).waitFor()
  await ticketPanel.getByRole('button', { name: 'Registrations', exact: true }).click()
  const chart = page.getByRole('group', { name: /Daily registrations/ })
  const days = chart.getByRole('button')
  await days.last().focus()
  await page.keyboard.press('ArrowLeft')
  assert.equal(await days.nth(5).getAttribute('aria-pressed'), 'true')
  await days.first().click()
  assert.equal(await days.first().getAttribute('aria-pressed'), 'true')
  const eventList = page.getByRole('region', { name: 'My events', exact: true })
  const mapBox = await map.boundingBox()
  const eventListBox = await eventList.boundingBox()
  assert.ok(mapBox && eventListBox && eventListBox.y >= mapBox.y + mapBox.height, 'My events should sit below the venue map')
  await page.getByRole('link', { name: 'Review changes for Photography Walk' }).click()
  await eventList.getByRole('link', { name: 'Photography Walk', exact: true }).waitFor()
  await eventList.getByLabel('Search your events').fill('')
  await eventList.getByRole('button', { name: 'Upcoming', exact: true }).click()
  await eventList.getByText('Date: soonest first', { exact: true }).waitFor()
  assert.match(await eventList.getByRole('row').nth(1).innerText(), /Open-Air Cinema/)
  await eventList.getByRole('button', { name: 'All events', exact: true }).click()
  await page.getByRole('navigation', { name: 'Preview role', exact: true }).getByRole('link', { name: 'Admin', exact: true }).click()
  await page.getByRole('link', { name: 'Review events', exact: false }).first().waitFor()
  assert.equal(await page.getByRole('navigation', { name: 'Preview role' }).getByRole('link', { name: 'Admin', exact: true }).getAttribute('aria-current'), 'page')
  await page.getByRole('region', { name: 'Approval queue' }).getByRole('link', { name: 'Show pending events' }).click()
  assert.equal(await page.getByRole('button', { name: 'Pending', exact: true }).getAttribute('aria-pressed'), 'true')
  await page.getByRole('button', { name: 'All events', exact: true }).click()
  await page.getByRole('navigation', { name: 'Preview role' }).getByRole('link', { name: 'Organiser', exact: true }).click()
  await page.getByRole('link', { name: 'Create event', exact: true }).waitFor()
  await page.getByLabel('Search your events').fill('Design for Everyone')
  await page.getByRole('region', { name: 'My events' }).getByRole('link', { name: 'Design for Everyone', exact: true }).waitFor()
  await page.getByLabel('Search your events').fill('')
  await page.evaluate(async () => { if (document.activeElement instanceof HTMLElement) document.activeElement.blur(); window.scrollTo(0, 0); await document.fonts.ready })
  const image = await page.screenshot({ type: 'jpeg', quality: 70, fullPage: true, animations: 'disabled' })
  console.log('LINEUP_SCREENSHOT_START:development-preview')
  console.log(image.toString('base64'))
  console.log('LINEUP_SCREENSHOT_END:development-preview')
  const issues = await page.evaluate(async () => {
    for (const portal of document.querySelectorAll('nextjs-portal')) {
      for (const button of portal.shadowRoot?.querySelectorAll('button') ?? []) {
        if (/\d+\s*Issue/.test(button.textContent ?? '')) button.click()
      }
    }
    await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))
    return [...document.querySelectorAll('nextjs-portal')].map(portal => [...(portal.shadowRoot?.children ?? [])].filter(e => e.tagName !== 'STYLE').map(e => e instanceof HTMLElement ? e.innerText : '').join('\n')).join('\n').slice(0, 10000)
  })
  console.log('DEV_PREVIEW_ISSUES ' + JSON.stringify(issues))
  await page.reload()
  await page.getByRole('region', { name: 'Development preview', exact: true }).waitFor()
  const sidebar = page.locator('.workspace-sidebar')
  const desktopSidebar = await sidebar.boundingBox()
  assert.ok(desktopSidebar && desktopSidebar.width >= 260, 'Desktop sidebar should have room for navigation labels')
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
  assert.ok(desktopSidebar.x > 0 && desktopSidebar.y > 0, 'Desktop sidebar should float inside the viewport')
  const body = page.locator('.workspace-body')
  const expandedBody = await body.boundingBox()
  await sidebar.getByRole('button', { name: 'Collapse sidebar' }).click()
  const expand = sidebar.getByRole('button', { name: 'Expand sidebar' })
  assert.equal(await expand.getAttribute('aria-expanded'), 'false')
  await sidebar.evaluate(async node => {
    await new Promise(requestAnimationFrame)
    await Promise.all(node.getAnimations().map(animation => animation.finished))
  })
  const rail = await sidebar.boundingBox()
  const collapsedBody = await body.boundingBox()
  assert.ok(rail && rail.width < 100 && expandedBody && collapsedBody && collapsedBody.x < expandedBody.x)
  assert.equal(await sidebar.getByRole('link', { name: 'My events' }).getAttribute('href'), '/dev-preview?role=organizer#events')
  await expand.click()
  assert.equal(await sidebar.getByRole('button', { name: 'Collapse sidebar' }).getAttribute('aria-expanded'), 'true')
  const header = page.locator('.workspace-topbar')
  await header.locator('summary').click()
  await header.getByRole('link', { name: 'Exit preview', exact: true }).waitFor()
  await page.keyboard.press('Escape')
  await header.getByRole('link', { name: 'Exit preview', exact: true }).waitFor({ state: 'hidden' })
  await page.keyboard.press('Control+k')
  const search = page.getByRole('dialog', { name: 'Search workspace', exact: true })
  const searchInput = search.getByRole('searchbox', { name: 'Find a workspace page' })
  await searchInput.fill('calendar')
  await search.getByRole('link', { name: 'Calendar', exact: true }).waitFor()
  await searchInput.press('Enter')
  await page.waitForURL('**#calendar')
  await search.waitFor({ state: 'hidden' })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  assert.equal(await sidebar.evaluate(node => getComputedStyle(node).transitionDuration), '0s')
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.setViewportSize({ width: 320, height: 812 })
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
  await page.getByRole('button', { name: 'Open navigation', exact: true }).click()
  await page.getByRole('dialog', { name: 'Workspace menu', exact: true }).getByRole('link', { name: 'Overview', exact: true }).click()
  await page.getByRole('region', { name: 'Development preview', exact: true }).waitFor()
  await page.goto(base + '/organizer')
  await page.waitForURL('**/login?next=*')
  assert.deepEqual(errors, [])
  console.log('PASS anonymous development preview, both roles, real-route protection, mobile layout and production 404')
} finally { await browser.close() }
