import assert from 'node:assert/strict'

const base = process.env.LINEUP_PREVIEW_TEST_URL
if (process.env.LINEUP_LOCAL_E2E !== '1' || !base || !['localhost', '127.0.0.1'].includes(new URL(base).hostname)) throw new Error('Development preview checks require an explicit loopback test URL.')
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ?? 'playwright')
const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
page.setDefaultTimeout(60000)
const errors = []
page.on('pageerror', error => errors.push(error.message))
try {
  const production = await page.request.get('http://localhost:3001/dev-preview')
  assert.equal(production.status(), 404, 'Production must not expose the development preview')
  assert.equal((await production.text()).includes('Sample data. Explore both dashboards'), false)
  await page.goto(base + '/login')
  await page.getByRole('link', { name: 'Preview without an account', exact: false }).click()
  await page.getByRole('region', { name: 'Development preview', exact: true }).waitFor()
  assert.equal(await page.getByTestId('metric-ticket').textContent(), '72')
  assert.equal(await page.getByTestId('metric-circle-check').textContent(), '18')
  await page.getByRole('link', { name: 'Create event', exact: true }).waitFor()
  await page.getByRole('navigation', { name: 'Preview role', exact: true }).getByRole('link', { name: 'Admin', exact: true }).click()
  await page.getByRole('link', { name: 'Review events', exact: false }).first().waitFor()
  assert.equal(await page.getByRole('navigation', { name: 'Preview role' }).getByRole('link', { name: 'Admin', exact: true }).getAttribute('aria-current'), 'page')
  await page.getByRole('navigation', { name: 'Preview role' }).getByRole('link', { name: 'Organiser', exact: true }).click()
  await page.getByRole('link', { name: 'Create event', exact: true }).waitFor()
  await page.getByLabel('Search your events').fill('Design for Everyone')
  await page.getByRole('region', { name: 'My events' }).getByRole('link', { name: 'Design for Everyone', exact: true }).waitFor()
  await page.getByLabel('Search your events').fill('')
  await page.evaluate(async () => { if (document.activeElement instanceof HTMLElement) document.activeElement.blur(); window.scrollTo(0, 0); await document.fonts.ready })
  const image = await page.screenshot({ type: 'jpeg', quality: 70, fullPage: true, animations: 'disabled' })
  console.log('LINEUP_SCREENSHOT_START:development-preview')
  console.log(image.toString('base64'))
  console.log('LINEUP_SCREENSHOT_END:development-preview')
  await page.setViewportSize({ width: 375, height: 812 })
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
  await page.getByRole('button', { name: 'Open navigation', exact: true }).click()
  await page.getByRole('dialog', { name: 'Workspace menu', exact: true }).getByRole('link', { name: 'Overview', exact: true }).click()
  await page.getByRole('region', { name: 'Development preview', exact: true }).waitFor()
  await page.goto(base + '/organizer')
  await page.waitForURL('**/login?next=*')
  assert.deepEqual(errors, [])
  console.log('PASS anonymous development preview, both roles, real-route protection, mobile layout and production 404')
} finally { await browser.close() }
